import { useEffect, useRef, useState } from 'react';
import {
  ActivityIndicator,
  FlatList,
  KeyboardAvoidingView,
  Platform,
  Pressable,
  StyleSheet,
  Text,
  TextInput,
  View,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';

import { useChat, type ChatTransport, type UIMessage } from '../hooks/useChat';

interface Props {
  transport: ChatTransport;
}

function Bubble({ message, streaming }: { message: UIMessage; streaming: boolean }) {
  const isUser = message.role === 'user';
  return (
    <View style={[styles.bubble, isUser ? styles.userBubble : styles.assistantBubble]}>
      {message.content === '' && streaming ? (
        <ActivityIndicator size="small" color="#6b7280" />
      ) : (
        <Text style={isUser ? styles.userText : styles.assistantText} selectable>
          {message.content}
        </Text>
      )}
    </View>
  );
}

export function ChatScreen({ transport }: Props) {
  const { messages, status, error, send, stop, reset } = useChat(transport);
  const [draft, setDraft] = useState('');
  const listRef = useRef<FlatList<UIMessage>>(null);
  const streaming = status === 'streaming';
  const lastId = messages[messages.length - 1]?.id;
  const lastLength = messages[messages.length - 1]?.content.length ?? 0;

  // Keep the newest text in view while a reply streams in.
  useEffect(() => {
    if (messages.length > 0) listRef.current?.scrollToEnd({ animated: false });
  }, [messages.length, lastLength]);

  const submit = () => {
    if (draft.trim() === '' || streaming) return;
    send(draft);
    setDraft('');
  };

  return (
    <SafeAreaView style={styles.screen}>
      <KeyboardAvoidingView
        style={styles.screen}
        behavior={Platform.OS === 'ios' ? 'padding' : undefined}
      >
        <View style={styles.header}>
          <Text style={styles.title} accessibilityRole="header">
            Chat
          </Text>
          <Pressable
            onPress={reset}
            disabled={messages.length === 0}
            accessibilityRole="button"
            accessibilityLabel="Start a new chat"
            hitSlop={8}
          >
            <Text style={[styles.headerAction, messages.length === 0 && styles.disabledText]}>
              New chat
            </Text>
          </Pressable>
        </View>

        <FlatList
          ref={listRef}
          data={messages}
          keyExtractor={(item) => item.id}
          renderItem={({ item }) => (
            <Bubble message={item} streaming={streaming && item.id === lastId} />
          )}
          contentContainerStyle={styles.list}
          keyboardShouldPersistTaps="handled"
          ListEmptyComponent={
            <Text style={styles.empty}>Ask a question to start the conversation.</Text>
          }
        />

        {error ? (
          <Text style={styles.error} accessibilityRole="alert">
            {error}
          </Text>
        ) : null}

        <View style={styles.composer}>
          <TextInput
            style={styles.input}
            value={draft}
            onChangeText={setDraft}
            placeholder="Message"
            placeholderTextColor="#9ca3af"
            multiline
            accessibilityLabel="Message"
          />
          {streaming ? (
            <Pressable
              style={[styles.button, styles.stopButton]}
              onPress={stop}
              accessibilityRole="button"
              accessibilityLabel="Stop the reply"
            >
              <Text style={styles.buttonText}>Stop</Text>
            </Pressable>
          ) : (
            <Pressable
              style={[styles.button, draft.trim() === '' && styles.buttonDisabled]}
              onPress={submit}
              disabled={draft.trim() === ''}
              accessibilityRole="button"
              accessibilityLabel="Send message"
            >
              <Text style={styles.buttonText}>Send</Text>
            </Pressable>
          )}
        </View>
        <Text style={styles.disclosure}>Replies are generated by AI and may be inaccurate.</Text>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  screen: { flex: 1, backgroundColor: '#ffffff' },
  header: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'space-between',
    paddingHorizontal: 16,
    paddingVertical: 12,
    borderBottomWidth: StyleSheet.hairlineWidth,
    borderBottomColor: '#d1d5db',
  },
  title: { fontSize: 20, fontWeight: '600', color: '#111827' },
  headerAction: { fontSize: 16, color: '#2563eb' },
  disabledText: { color: '#9ca3af' },
  list: { padding: 16, gap: 10, flexGrow: 1 },
  empty: { marginTop: 48, textAlign: 'center', color: '#6b7280', fontSize: 16 },
  bubble: { maxWidth: '85%', borderRadius: 16, paddingHorizontal: 14, paddingVertical: 10 },
  userBubble: { alignSelf: 'flex-end', backgroundColor: '#2563eb' },
  assistantBubble: { alignSelf: 'flex-start', backgroundColor: '#f3f4f6' },
  userText: { color: '#ffffff', fontSize: 16, lineHeight: 22 },
  assistantText: { color: '#111827', fontSize: 16, lineHeight: 22 },
  error: {
    marginHorizontal: 16,
    marginBottom: 8,
    padding: 10,
    borderRadius: 8,
    backgroundColor: '#fef2f2',
    color: '#b91c1c',
    fontSize: 14,
  },
  composer: {
    flexDirection: 'row',
    alignItems: 'flex-end',
    gap: 8,
    paddingHorizontal: 12,
    paddingTop: 8,
    borderTopWidth: StyleSheet.hairlineWidth,
    borderTopColor: '#d1d5db',
  },
  input: {
    flex: 1,
    minHeight: 44,
    maxHeight: 140,
    paddingHorizontal: 14,
    paddingVertical: 10,
    borderRadius: 22,
    backgroundColor: '#f3f4f6',
    color: '#111827',
    fontSize: 16,
  },
  button: {
    minWidth: 64,
    height: 44,
    borderRadius: 22,
    alignItems: 'center',
    justifyContent: 'center',
    paddingHorizontal: 16,
    backgroundColor: '#2563eb',
  },
  stopButton: { backgroundColor: '#374151' },
  buttonDisabled: { backgroundColor: '#93c5fd' },
  buttonText: { color: '#ffffff', fontSize: 16, fontWeight: '600' },
  disclosure: { textAlign: 'center', color: '#6b7280', fontSize: 12, paddingVertical: 8 },
});
